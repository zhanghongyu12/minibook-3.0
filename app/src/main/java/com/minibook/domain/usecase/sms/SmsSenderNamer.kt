package com.minibook.domain.usecase.sms

/**
 * 从短信正文猜**发送机构名**（docs/15 第 2 条，2026-10-13）。
 *
 * 背景：短信发送方是号码（95xxx 端口、106 通用端口），号码本身无法告诉用户「这是哪家银行」；
 * 而用户要「多家银行只导入指定一家」，所以来源清单必须显示**人能认出的名字**。
 *
 * 口径：
 * - 纯函数、无 Android 依赖 → JVM 可测；
 * - **只输出机构名**（如「建设银行」），不输出短信原文的任何其他部分（DEC-026）；
 * - 猜不出就返回 null，UI 回退显示号码（绝不猜错后硬写一个名字）。
 */
object SmsSenderNamer {

    /**
     * 已知机构名（长名在前：先匹配「中国邮政储蓄银行」，再匹配「中国银行」，避免被短名抢走）。
     *
     * 只收**全国性、可辨识**的机构与平台；区域小行不通用时靠正文 `【】` 签名兜底。
     */
    private val INSTITUTIONS: List<String> = listOf(
        // 银行
        "中国工商银行", "中国建设银行", "中国农业银行", "中国银行", "交通银行", "中国邮政储蓄银行",
        "邮政储蓄银行", "招商银行", "中信银行", "浦发银行", "上海浦东发展银行", "民生银行", "光大银行",
        "兴业银行", "平安银行", "华夏银行", "广发银行", "北京银行", "上海银行", "江苏银行", "宁波银行",
        "南京银行", "浙商银行", "恒丰银行", "渤海银行", "农商银行", "农村商业银行", "农村信用",
        "村镇银行", "工商银行", "建设银行", "农业银行", "邮储银行",
        // 支付/互联网金融
        "支付宝", "财付通", "微信支付", "云闪付", "银联", "京东支付", "美团支付", "抖音支付",
        "天翼支付", "网商银行", "微众银行", "花呗", "借呗",
        // 常见平台/运营商（账单类通知也会出现）
        "中国移动", "中国联通", "中国电信", "京东", "拼多多", "顺丰速运", "菜鸟驿站", "滴滴出行",
    ).sortedByDescending { it.length }

    /** 正文开头 `【机构名】` 签名（营销/账单短信都常见），限制长度以免把整句当机构名。 */
    private val BRACKET_SIGNATURE = Regex("^[【\\[]([^】\\]]{2,12})[】\\]]")

    /**
     * @param sender 发送方号码（本函数只在正文猜不出时用于兜底返回 null，不参与判断）。
     * @param body 短信正文。
     * @return 机构名；猜不出返回 null。
     */
    fun name(sender: String, body: String): String? {
        INSTITUTIONS.firstOrNull { it in body }?.let { return it }
        return BRACKET_SIGNATURE.find(body.trim())?.groupValues?.getOrNull(1)?.trim()?.takeIf { it.isNotEmpty() }
    }
}
